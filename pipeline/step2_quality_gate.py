def _format_validation_error(error: dict[str, Any]) -> str:
    """
    Convert one Pydantic validation error into a compact readable message.
    """

    location = ".".join(
        str(part)
        for part in error.get("loc", ())
    )

    message = error.get("msg", "validation error")

    if location:
        return f"{location}: {message}"

    return str(message)


def validate_structure(
    raw_record: dict[str, Any],
) -> tuple[TraceRecord | None, list[str]]:
    """
    Validate one Step 1 record using the TraceRecord Pydantic model.

    Step 1 writes a TraceRecord whose qa_item field contains the QAItem.
    This helper captures schema failures without terminating the full run.
    """

    try:
        return TraceRecord.model_validate(raw_record), []

    except ValidationError as exc:
        return (
            None,
            [
                _format_validation_error(error)
                for error in exc.errors()
            ],
        )

    except (TypeError, ValueError) as exc:
        return None, [str(exc)]


# ============================================================
# Question Normalization / Exact Deduplication
# ============================================================


def normalize_question(question: str) -> str:
    """
    Normalize a question for exact duplicate detection.

    Normalization:
        - lowercase
        - remove punctuation
        - collapse whitespace
        - trim whitespace
    """

    normalized = question.lower()
    normalized = re.sub(r"[^\w\s]", "", normalized)
    normalized = re.sub(r"\s+", " ", normalized)

    return normalized.strip()


def find_exact_duplicates(
    items: list[QAItem],
) -> dict[int, int]:
    """
    Detect duplicate questions after normalization.

    Returns:
        {
            duplicate_validated_index: original_validated_index
        }
    """

    # The first normalized question is canonical; later matches reference it.
    seen: dict[str, int] = {}
    duplicates: dict[int, int] = {}

    for index, item in enumerate(items):
        normalized = normalize_question(item.question)

        if normalized in seen:
            duplicates[index] = seen[normalized]
        else:
            seen[normalized] = index

    return duplicates


# ============================================================
# Semantic Deduplication
# ============================================================


def cosine_similarity(
    vector_a: list[float],
    vector_b: list[float],
) -> float:
    """
    Calculate cosine similarity between two embedding vectors.
    """

    if len(vector_a) != len(vector_b):
        raise ValueError(
            "Embedding vectors have different dimensions: "
            f"{len(vector_a)} != {len(vector_b)}"
        )

    dot_product = sum(
        a * b
        for a, b in zip(vector_a, vector_b)
    )

    magnitude_a = math.sqrt(
        sum(value * value for value in vector_a)
    )

    magnitude_b = math.sqrt(
        sum(value * value for value in vector_b)
    )

    # A zero vector has no direction; treat it as no similarity to avoid division.
    if magnitude_a == 0 or magnitude_b == 0:
        return 0.0

    return dot_product / (magnitude_a * magnitude_b)


def find_semantic_duplicates(
    items: list[QAItem],
    exact_duplicates: dict[int, int],
    threshold: float = SEMANTIC_DEDUP_THRESHOLD,
) -> dict[int, dict[str, Any]]:
    """
    Detect semantically similar questions using embeddings.

    Exact duplicates are excluded from comparisons because they were identified by
    the exact-deduplication stage.

    Earlier semantic duplicates are also skipped as comparison targets so
    duplicate chains point back to a canonical earlier item.
    """

    if len(items) < 2:
        return {}

    questions = [
        item.question
        for item in items
    ]

    # Embed questions only, including exact duplicates to preserve index alignment.
    # Answers do not participate in similarity scoring.
    embeddings = create_embeddings(questions)

    if len(embeddings) != len(items):
        raise ValueError(
            "Embedding provider returned an unexpected number of "
            f"embeddings. Expected {len(items)}, "
            f"received {len(embeddings)}."
        )

    duplicates: dict[int, dict[str, Any]] = {}

    # Compare each question with earlier canonical questions across all categories.
    # This pairwise scan has quadratic comparison cost as the batch grows.
    for current_index in range(1, len(items)):
        if current_index in exact_duplicates:
            continue

        best_match_index: int | None = None
        best_similarity = -1.0

        for previous_index in range(current_index):
            if previous_index in exact_duplicates:
                continue

            if previous_index in duplicates:
                continue

            similarity = cosine_similarity(
                embeddings[current_index],
                embeddings[previous_index],
            )

            if similarity > best_similarity:
                best_similarity = similarity
                best_match_index = previous_index

        # Decide using full precision; round only the similarity saved for reporting.
        if (
            best_match_index is not None
            and best_similarity >= threshold
        ):
            duplicates[current_index] = {
                "original_index": best_match_index,
                "similarity": round(best_similarity, 4),
            }

    return duplicates


# ============================================================
# Heuristic Quality Checks
# ============================================================


def check_answer_completeness(
    item: QAItem,
) -> tuple[bool, str | None]:
    """
    Lightweight D1 heuristic.
    """

    if not item.answer.strip():
        return False, "answer is empty"

    if len(item.steps) < 3:
        return False, "fewer than 3 repair steps"

    return True, None


def check_safety_specificity(
    item: QAItem,
) -> tuple[bool, str | None]:
    """
    Lightweight D2 heuristic.

    Checks:
        - minimum safety information length
        - rejects generic-only safety guidance
    """

    safety = item.safety_info.strip()

    if len(safety) < MIN_SAFETY_INFO_LENGTH:
        return (
            False,
            "safety_info shorter than "
            f"{MIN_SAFETY_INFO_LENGTH} characters",
        )

    normalized = safety.lower().strip(" .!")

    generic_phrases = {
        phrase.lower().strip(" .!")
        for phrase in GENERIC_SAFETY_PHRASES
    }

    if normalized in generic_phrases:
        return (
            False,
            "safety_info contains only generic safety advice",
        )

    return True, None


def check_tool_realism(
    item: QAItem,
) -> tuple[bool, str | None]:
    """
    Lightweight D3 heuristic.

    Checks:
        - at least one required tool is specified
        - rejects unrealistic/professional-only tools listed in tools_required
        - rejects unrealistic/professional-only tools mentioned in the answer
    """

    if not item.tools_required:
        return (
            False,
            "no tools required specified",
        )

    tools_text = " ".join(
        str(tool)
        for tool in item.tools_required
    ).lower()

    answer_text = item.answer.lower()

    for phrase in UNREALISTIC_TOOL_PHRASES:
        normalized_phrase = phrase.lower()

        if normalized_phrase in tools_text:
            return (
                False,
                f"unrealistic tool listed in tools_required: {phrase}",
            )

        if normalized_phrase in answer_text:
            return (
                False,
                f"unrealistic tool mentioned in answer: {phrase}",
            )

    return True, None


def check_scope_appropriateness(
    item: QAItem,
) -> tuple[bool, str | None]:
    """
    Lightweight D4 heuristic.

    Step 2 intentionally performs only a basic scope check.
    Detailed homeowner-scope judgment belongs to later human/LLM review.
    """

    if not item.equipment_problem.strip():
        return False, "equipment_problem is empty"

    return True, None


def check_context_clarity(
    item: QAItem,
) -> tuple[bool, str | None]:
    """
    Lightweight D5 heuristic.
    """

    if not item.question.strip():
        return False, "question is empty"

    if not item.equipment_problem.strip():
        return False, "equipment_problem is empty"

    return True, None


def check_tip_usefulness(
    item: QAItem,
) -> tuple[bool, str | None]:
    """
    Lightweight D6 heuristic.

    Requires at least one sufficiently descriptive tip.
    """

    if not item.tips:
        return False, "no tips provided"

    useful_tips = [
        tip
        for tip in item.tips
        if len(tip.strip()) >= MIN_TIP_LENGTH
    ]

    if not useful_tips:
        return (
            False,
            "no tip is at least "
            f"{MIN_TIP_LENGTH} characters",
        )

    return True, None


def run_heuristic_checks(
    item: QAItem,
) -> dict[str, dict[str, Any]]:
    """
    Run all six lightweight Step 2 quality heuristics.
    """

    checks = {
        "D1_answer_completeness":
            check_answer_completeness(item),

        "D2_safety_specificity":
            check_safety_specificity(item),

        "D3_tool_realism":
            check_tool_realism(item),

        "D4_scope_appropriateness":
            check_scope_appropriateness(item),

        "D5_context_clarity":
            check_context_clarity(item),

        "D6_tip_usefulness":
            check_tip_usefulness(item),
    }

    return {
        dimension: {
            "passed": passed,
            "reason": reason,
        }
        for dimension, (passed, reason) in checks.items()
    }


# ============================================================
# Category Distribution
# ============================================================


def check_category_distribution(
    traces: list[TraceRecord],
) -> dict[str, Any]:
    """
    Compare category distribution with the configured uniform-share bounds.

    Category belongs to TraceRecord, not QAItem.

    This is a dataset-level check. A category-distribution failure does not
    automatically fail every individual Q&A record.
    """

    total = len(traces)

    counts = Counter(
        trace.category
        for trace in traces
    )

    expected_categories = set(CATEGORIES)

    categories: dict[str, Any] = {}
    overall_pass = True

    for category in sorted(expected_categories):
        count = counts.get(category, 0)

        percentage = (
            count / total
            if total > 0
            else 0.0
        )

        passed = (
            MIN_CATEGORY_PERCENTAGE
            <= percentage
            <= MAX_CATEGORY_PERCENTAGE
        )

        if not passed:
            overall_pass = False

        categories[category] = {
            "count": count,
            "percentage": round(percentage, 4),
            "target_percentage":
                TARGET_CATEGORY_PERCENTAGE,
            "minimum_percentage":
                MIN_CATEGORY_PERCENTAGE,
            "maximum_percentage":
                MAX_CATEGORY_PERCENTAGE,
            "passed": passed,
        }

    unexpected_categories = sorted(
        set(counts.keys())
        - expected_categories
    )

    if unexpected_categories:
        overall_pass = False

    return {
        "passed": overall_pass,
        "total_records": total,
        "categories": categories,
        "unexpected_categories":
            unexpected_categories,
    }


# ============================================================
# Reporting Helpers
