def _build_exact_duplicate_report(
    exact_duplicates: dict[int, int],
    validated_items: list[QAItem],
    validated_to_original: list[int],
) -> list[dict[str, Any]]:
    """
    Convert exact duplicate indexes into report-friendly records.
    """

    return [
        {
            "duplicate_record_index":
                validated_to_original[duplicate_index],
            "original_record_index":
                validated_to_original[original_index],
            "duplicate_question":
                validated_items[duplicate_index].question,
            "original_question":
                validated_items[original_index].question,
        }
        for duplicate_index, original_index
        in exact_duplicates.items()
    ]


def _build_semantic_duplicate_report(
    semantic_duplicates: dict[int, dict[str, Any]],
    validated_items: list[QAItem],
    validated_to_original: list[int],
    semantic_threshold: float,
) -> list[dict[str, Any]]:
    """
    Convert semantic duplicate indexes into report-friendly records.
    """

    report: list[dict[str, Any]] = []

    for duplicate_index, duplicate_info in semantic_duplicates.items():
        original_index = duplicate_info["original_index"]

        report.append(
            {
                "duplicate_record_index":
                    validated_to_original[duplicate_index],
                "original_record_index":
                    validated_to_original[original_index],
                "duplicate_question":
                    validated_items[duplicate_index].question,
                "original_question":
                    validated_items[original_index].question,
                "similarity":
                    duplicate_info["similarity"],
                "threshold":
                    semantic_threshold,
            }
        )

    return report


# ============================================================
# Main Quality Gate
# ============================================================


def run_quality_gate(
    input_file: Path,
    output_file: Path,
    report_file: Path,
    enable_semantic_dedup: bool = True,
    semantic_threshold: float = SEMANTIC_DEDUP_THRESHOLD,
) -> dict[str, Any]:
    """
    Execute Step 2.
    """

    raw_records = read_jsonl(input_file)

    print(
        f"Loaded {len(raw_records)} records "
        f"from {input_file}"
    )

    # --------------------------------------------------------
    # 1. Structural validation
    # --------------------------------------------------------

    validated_traces: list[TraceRecord] = []
    validated_items: list[QAItem] = []
    # Validation removes some items from comparison arrays. Translate their
    # indexes back to original file positions for duplicate reports and output.
    validated_to_original: list[int] = []

    structural_failures: dict[
        int,
        list[str],
    ] = {}

    for original_index, raw_record in enumerate(raw_records):
        trace, failures = validate_structure(raw_record)

        if trace is None:
            structural_failures[original_index] = failures
            continue

        validated_to_original.append(original_index)
        validated_traces.append(trace)
        validated_items.append(trace.qa_item)

    # --------------------------------------------------------
    # 2. Exact duplicate detection
    # --------------------------------------------------------

    exact_duplicates = find_exact_duplicates(
        validated_items
    )

    # --------------------------------------------------------
    # 3. Semantic duplicate detection
    # --------------------------------------------------------

    semantic_duplicates: dict[
        int,
        dict[str, Any],
    ] = {}

    if (
        enable_semantic_dedup
        and len(validated_items) > 1
    ):
        semantic_duplicates = find_semantic_duplicates(
            validated_items,
            exact_duplicates,
            semantic_threshold,
        )

    # --------------------------------------------------------
    # 4. Build per-item gate results
    # --------------------------------------------------------

    records_by_original_index: dict[
        int,
        dict[str, Any],
    ] = {}

    passed_count = 0
    failed_count = 0

    # Preserve invalid records for auditing, without running content checks on
    # them. Their duplicate flags are unset results, not evidence of uniqueness.
    for original_index, failures in structural_failures.items():
        gate_record = {
            **raw_records[original_index],
            "gate_pass": False,
            "gate_failures": failures,
            "gate_result": {
                "passed": False,
                "structural_validation_passed": False,
                "exact_duplicate": False,
                "exact_duplicate_info": None,
                "semantic_duplicate": False,
                "semantic_duplicate_info": None,
                "heuristics": {},
                "failure_reasons": failures,
            },
        }

        records_by_original_index[
            original_index
        ] = gate_record

        failed_count += 1

    # Structurally valid records.
    for validated_index, item in enumerate(validated_items):
        original_index = validated_to_original[
            validated_index
        ]

        trace = validated_traces[
            validated_index
        ]

        failure_reasons: list[str] = []

        # Exact duplicate.
        exact_duplicate = (
            validated_index
            in exact_duplicates
        )

        exact_duplicate_info = None

        if exact_duplicate:
            original_validated_index = exact_duplicates[
                validated_index
            ]

            exact_duplicate_info = {
                "original_record_index":
                    validated_to_original[
                        original_validated_index
                    ],
                "original_question":
                    validated_items[
                        original_validated_index
                    ].question,
            }

            failure_reasons.append(
                "exact_duplicate_question"
            )

        # Semantic duplicate.
        semantic_duplicate = (
            validated_index
            in semantic_duplicates
        )

        semantic_duplicate_info = None

        if semantic_duplicate:
            semantic_info = semantic_duplicates[
                validated_index
            ]

            original_validated_index = semantic_info[
                "original_index"
            ]

            semantic_duplicate_info = {
                "original_record_index":
                    validated_to_original[
                        original_validated_index
                    ],
                "original_question":
                    validated_items[
                        original_validated_index
                    ].question,
                "similarity":
                    semantic_info["similarity"],
                "threshold":
                    semantic_threshold,
            }

            failure_reasons.append(
                "semantic_duplicate_question"
            )

        # Heuristic quality checks.
        heuristic_results = run_heuristic_checks(
            item
        )

        for dimension, result in heuristic_results.items():
            if result["passed"]:
                continue

            failure_reasons.append(
                f"{dimension}: {result['reason']}"
            )

        # Every duplicate and heuristic check must pass for individual acceptance.
        item_passed = not failure_reasons

        if item_passed:
            passed_count += 1
        else:
            failed_count += 1

        # Preserve the complete Step 1 TraceRecord and add/update
        # Step 2 gate information.
        gate_record = trace.model_dump()

        gate_record["gate_pass"] = item_passed
        gate_record["gate_failures"] = failure_reasons
        gate_record["gate_result"] = {
            "passed": item_passed,
            "structural_validation_passed": True,
            "exact_duplicate":
                exact_duplicate,
            "exact_duplicate_info":
                exact_duplicate_info,
            "semantic_duplicate":
                semantic_duplicate,
            "semantic_duplicate_info":
                semantic_duplicate_info,
            "heuristics":
                heuristic_results,
            "failure_reasons":
                failure_reasons,
        }

        records_by_original_index[
            original_index
        ] = gate_record

    # Restore exact Step 1 order.
    gated_records = [
        records_by_original_index[index]
        for index in range(len(raw_records))
    ]

    # --------------------------------------------------------
    # 5. Category distribution
    # --------------------------------------------------------

    # Measure structurally valid records before duplicate/heuristic filtering.
    # Batch balance can therefore differ from the accepted subset's balance.
    category_distribution = check_category_distribution(
        validated_traces
    )

    # --------------------------------------------------------
    # 6. Dataset-level metrics and reports
    # --------------------------------------------------------

    total_records = len(raw_records)
    structurally_valid_count = len(
        validated_traces
    )

    # Both batch rates use all loaded records, including structural failures.
    # Empty batches report zero rates rather than causing division by zero.
    structural_validation_rate = (
        structurally_valid_count / total_records
        if total_records
        else 0.0
    )

    gate_pass_rate = (
        passed_count / total_records
        if total_records
        else 0.0
    )

    exact_duplicate_report = (
        _build_exact_duplicate_report(
            exact_duplicates,
            validated_items,
            validated_to_original,
        )
    )

    semantic_duplicate_report = (
        _build_semantic_duplicate_report(
            semantic_duplicates,
            validated_items,
            validated_to_original,
            semantic_threshold,
        )
    )

    report = {
        "step": 2,
        "step_name": "data_quality_gate",
        "timestamp_utc":
            datetime.now(
                timezone.utc
            ).isoformat(),
        "input_file":
            str(input_file),
        "output_file":
            str(output_file),
        "report_file":
            str(report_file),
        "total_records":
            total_records,

        "structural_validation": {
            "valid_count":
                structurally_valid_count,
            "invalid_count":
                len(structural_failures),
            "validation_rate":
                round(
                    structural_validation_rate,
                    4,
                ),
            "target_rate":
                STRUCTURAL_VALIDATION_TARGET,
            "passed_target":
                structural_validation_rate
                >= STRUCTURAL_VALIDATION_TARGET,
            "failures":
                structural_failures,
        },

        "exact_deduplication": {
            "duplicate_count":
                len(exact_duplicates),
            "duplicates":
                exact_duplicate_report,
        },

        "semantic_deduplication": {
            "enabled":
                enable_semantic_dedup,
            "threshold":
                semantic_threshold,
            "duplicate_count":
                len(semantic_duplicates),
            "duplicates":
                semantic_duplicate_report,
        },

        "category_distribution":
            category_distribution,

        "quality_gate": {
            "passed_count":
                passed_count,
            "failed_count":
                failed_count,
            "pass_rate":
                round(
                    gate_pass_rate,
                    4,
                ),
        },
    }

    # --------------------------------------------------------
    # 7. Write artifacts
    # --------------------------------------------------------

    # Gated output retains rejections; Step 3 filters by gate_pass. The report
    # exposes batch checks for main.py's `all` command to decide whether to stop.
    write_jsonl(
        output_file,
        gated_records,
    )

    write_json(
        report_file,
        report,
    )

    # --------------------------------------------------------
    # 8. Console summary
    # --------------------------------------------------------

    print()
    print("Step 2 - Data Quality Gate")
    print("--------------------------")
    print(f"Input file:           {input_file}")
    print(f"Input records:        {total_records}")
    print(f"Structurally valid:   {structurally_valid_count}")
    print(f"Structural failures:  {len(structural_failures)}")
    print(f"Exact duplicates:     {len(exact_duplicates)}")

    if enable_semantic_dedup:
        print(f"Semantic duplicates:  {len(semantic_duplicates)}")
        print(f"Semantic threshold:   {semantic_threshold}")
    else:
        print("Semantic dedup:        disabled")

    print(f"Gate passed:          {passed_count}")
    print(f"Gate failed:          {failed_count}")
    print(
        "Category dist pass:   "
        f"{category_distribution['passed']}"
    )
    print()
    print(f"Gated output: {output_file}")
    print(f"Gate report:  {report_file}")

    return report


