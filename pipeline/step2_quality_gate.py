def parse_args() -> argparse.Namespace:
    """
    Parse Step 2 command-line arguments.
    """

    parser = argparse.ArgumentParser(
        description=(
            "Step 2 - Validate generated DIY repair "
            "Q&A data."
        )
    )

    parser.add_argument(
        "--input",
        type=Path,
        default=None,
        help=(
            "Optional input JSONL file. If omitted, Step 2 "
            "uses the generated_qa_<timestamp>.jsonl file "
            "with the greatest timestamp in BASELINE_DIR."
        ),
    )

    parser.add_argument(
        "--no-semantic-dedup",
        action="store_true",
        help=(
            "Disable embedding-based semantic "
            "duplicate detection."
        ),
    )

    parser.add_argument(
        "--semantic-threshold",
        type=float,
        default=SEMANTIC_DEDUP_THRESHOLD,
        help=(
            "Cosine similarity threshold used for "
            "semantic duplicate detection. "
            f"Default: {SEMANTIC_DEDUP_THRESHOLD}"
        ),
    )

    return parser.parse_args()


def main() -> None:
    """
    Command-line entry point for Step 2.
    """

    args = parse_args()

    input_file = resolve_input_file(
        cli_input=args.input,
        baseline_dir=Path(BASELINE_DIR),
    )

    output_dir = input_file.parent

    timestamp = datetime.now(
        timezone.utc
    ).strftime(
        OUTPUT_TIMESTAMP_FORMAT
    )

    output_file = (
        output_dir
        / f"gated_{timestamp}.jsonl"
    )

    report_file = (
        output_dir
        / f"gate_report_{timestamp}.json"
    )

    run_quality_gate(
        input_file=input_file,
        output_file=output_file,
        report_file=report_file,
        enable_semantic_dedup=(
            not args.no_semantic_dedup
        ),
        semantic_threshold=(
            args.semantic_threshold
        ),
    )


if __name__ == "__main__":
    main()
