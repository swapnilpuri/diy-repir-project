"""
Main entry point for the Home DIY Repair Synthetic Q&A pipeline.

The pipeline uses timestamped artifacts:

    Step 1
    generated_qa_<timestamp>.jsonl
              |
              v
    Step 2
    gated_<timestamp>.jsonl
    gate_report_<timestamp>.json
              |
              v
    Step 3
    human_labeled_<timestamp>.jsonl
              |
              v
    Step 4
    judged_<timestamp>.jsonl
              |
              v
    Step 5
    analysis_<timestamp>.json
    + visualization PNG files
              |
              v
    Step 6
    iteration_log_<timestamp>.json

Each step can be executed independently.

When --input is omitted, the latest timestamped artifact from
the preceding step is used.

The "all" command passes the exact artifact generated by each
step directly to the next step.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
from pathlib import Path

from config.settings import (
    BASELINE_DIR,
    CORRECTED_DIR,
    SEMANTIC_DEDUP_THRESHOLD,
)

from utils.artifact_utils import (
    TIMESTAMP_FORMAT,
    resolve_input_file,
    find_latest_timestamped_file,
)


# ============================================================
# Common Helpers
# ============================================================


def get_data_directory(corrected: bool) -> Path:
    """
    Return the directory for the requested run type.
    """

    directory = (
        CORRECTED_DIR
        if corrected
        else BASELINE_DIR
    )

    return Path(directory).expanduser().resolve()


def create_timestamp() -> str:
    """
    Create the standard timestamp used by pipeline artifacts.
    """

    return datetime.now(
        timezone.utc
    ).strftime(
        TIMESTAMP_FORMAT
    )


def create_output_file(
    directory: Path,
    prefix: str,
    suffix: str,
) -> Path:
    """
    Create a timestamped artifact path.
    """

    timestamp = create_timestamp()

    return (
        directory
        / f"{prefix}{timestamp}{suffix}"
    )


# ============================================================
# Step 1
# ============================================================


def run_step1(
    count_per_category: int,
    corrected: bool,
    guidance: str | None,
) -> Path:
    """
    Run Step 1 and return the exact generated artifact.

    Step 1 currently creates:

        generated_qa_<timestamp>.jsonl

    Since the original generate() function does not need to know
    about subsequent steps, main.py resolves the artifact after
    generation and returns it to the pipeline.
    """

    from pipeline.step1_generate import generate_qa_allitems

    directory = get_data_directory(
        corrected
    )

    generate_qa_allitems(
        count_per_category,
        corrected,
        guidance,
    )

    generated_file = (
        find_latest_timestamped_file(
            directory=directory,
            prefix="generated_qa_",
            suffix=".jsonl",
        )
    )

    print()
    print(
        f"Step 1 artifact: {generated_file}"
    )

    return generated_file


# ============================================================
# Step 2
# ============================================================


def run_step2(
    input_file: Path,
    corrected: bool,
    enable_semantic_dedup: bool = True,
    semantic_threshold: float = SEMANTIC_DEDUP_THRESHOLD,
) -> tuple[Path, Path, dict]:
    """
    Run Step 2 against a specific Step 1 artifact.

    Returns:

        gated_file
        gate_report_file
        gate_report
    """

    from pipeline.step2_quality_gate import (
        run_quality_gate,
    )

    directory = get_data_directory(
        corrected
    )

    # If an explicit Step 1 artifact is supplied,
    # keep Step 2 artifacts beside it.
    output_directory = input_file.parent

    gated_file = create_output_file(
        output_directory,
        "gated_",
        ".jsonl",
    )

    report_file = create_output_file(
        output_directory,
        "gate_report_",
        ".json",
    )

    report = run_quality_gate(
        input_file=input_file,
        output_file=gated_file,
        report_file=report_file,
        enable_semantic_dedup=(
            enable_semantic_dedup
        ),
        semantic_threshold=(
            semantic_threshold
        ),
    )

    return (
        gated_file,
        report_file,
        report,
    )


# ============================================================
# Step 3
# ============================================================


def run_step3(
    input_file: Path,
    label_count: int,
) -> Path:
    """
    Run Step 3 human labeling.

    The input must be the Step 2 gated artifact:

        gated_<timestamp>.jsonl

    Only records that passed Step 2 are included in the
    Step 3 output.
    """

    from pipeline.step3_human_label import (
        run_human_labeling,
    )

    output_file = create_output_file(
        input_file.parent,
        "human_labeled_",
        ".jsonl",
    )

    return run_human_labeling(
        input_file=input_file,
        output_file=output_file,
        label_count=label_count,
    )


# ============================================================
# Step 4
# ============================================================


def run_step4(
    input_file: Path,
) -> Path:
    """
    Run Step 4 LLM-as-Judge.

    Input:

        human_labeled_<timestamp>.jsonl

    Output:

        judged_<timestamp>.jsonl
    """

    from pipeline.step4_llm_judge import (
        run_llm_judge,
    )

    output_file = create_output_file(
        input_file.parent,
        "judged_",
        ".jsonl",
    )

    return run_llm_judge(
        input_file=input_file,
        output_file=output_file,
    )


# ============================================================
# Step 5
# ============================================================


def run_step5(
    input_file: Path,
) -> Path:
    """
    Run Step 5 analysis and visualization.

    Input:

        judged_<timestamp>.jsonl

    Output:

        analysis_<timestamp>.json

    Charts are written under:

        visualizations/
    """

    from pipeline.step5_analysis import (
        analyze,
    )

    timestamp = create_timestamp()

    output_file = (
        input_file.parent
        / f"analysis_{timestamp}.json"
    )

    chart_directory = (
        input_file.parent
        / "visualizations"
    )

    return analyze(
        input_file=input_file,
        output_file=output_file,
        chart_dir=chart_directory,
        timestamp=timestamp,
    )


# ============================================================
# Step 6
# ============================================================


def run_step6(
    input_file: Path,
) -> Path:
    """
    Run Step 6 iteration analysis.

    Input:

        analysis_<timestamp>.json

    Output:

        iteration_log_<timestamp>.json

    Step 6 first evaluates Phase A judge calibration.
    Phase B is evaluated only when the judge meets the
    configured human/judge agreement threshold.
    """

    from pipeline.step6_iteration import (
        run_iteration,
    )

    output_file = create_output_file(
        input_file.parent,
        "iteration_log_",
        ".json",
    )

    return run_iteration(
        input_file=input_file,
        output_file=output_file,
    )


# ============================================================
# Complete Pipeline
# ============================================================


def run_all_steps(
    count_per_category: int,
    corrected: bool,
    guidance: str | None,
    human_label_count: int,
    enable_semantic_dedup: bool,
    semantic_threshold: float,
) -> None:
    """
    Run Steps 1 through 6 sequentially.

    The exact artifact returned by each step is passed
    directly to the next step.

    This avoids accidentally processing an unrelated file
    when multiple timestamped artifacts exist.
    """

    print()
    print("=" * 60)
    print("STEP 1 - SYNTHETIC Q&A GENERATION")
    print("=" * 60)

    generated_file = run_step1(
        count_per_category=count_per_category,
        corrected=corrected,
        guidance=guidance,
    )

    print()
    print("=" * 60)
    print("STEP 2 - DATA QUALITY GATE")
    print("=" * 60)

    (
        gated_file,
        gate_report_file,
        gate_report,
    ) = run_step2(
        input_file=generated_file,
        corrected=corrected,
        enable_semantic_dedup=(
            enable_semantic_dedup
        ),
        semantic_threshold=(
            semantic_threshold
        ),
    )

    # --------------------------------------------------------
    # Do not continue if critical batch-level gate checks fail.
    # --------------------------------------------------------

    structural_pass = (
        gate_report
        .get("structural_validation", {})
        .get("passed_target", False)
    )

    distribution_pass = (
        gate_report
        .get("category_distribution", {})
        .get("passed", False)
    )

    if not structural_pass:

        raise RuntimeError(
            "Step 2 structural-validation target was not met. "
            "Pipeline stopped before labeling. "
            f"See: {gate_report_file}"
        )

    if not distribution_pass:

        raise RuntimeError(
            "Step 2 category-distribution check failed. "
            "Pipeline stopped before labeling. "
            f"See: {gate_report_file}"
        )

    print()
    print("=" * 60)
    print("STEP 3 - HUMAN REVIEW")
    print("=" * 60)

    human_file = run_step3(
        input_file=gated_file,
        label_count=human_label_count,
    )

    print()
    print("=" * 60)
    print("STEP 4 - LLM-AS-JUDGE")
    print("=" * 60)

    judged_file = run_step4(
        input_file=human_file,
    )

    print()
    print("=" * 60)
    print("STEP 5 - ANALYSIS & VISUALIZATION")
    print("=" * 60)

    analysis_file = run_step5(
        input_file=judged_file,
    )

    print()
    print("=" * 60)
    print("STEP 6 - ITERATION ANALYSIS")
    print("=" * 60)

    iteration_file = run_step6(
        input_file=analysis_file,
    )

    print()
    print("=" * 60)
    print("PIPELINE COMPLETE")
    print("=" * 60)

    print(
        f"Step 1: {generated_file}"
    )

    print(
        f"Step 2: {gated_file}"
    )

    print(
        f"Gate report: {gate_report_file}"
    )

    print(
        f"Step 3: {human_file}"
    )

    print(
        f"Step 4: {judged_file}"
    )

    print(
        f"Step 5: {analysis_file}"
    )

    print(
        f"Step 6: {iteration_file}"
    )


# ============================================================
# Argument Parser
# ============================================================


def build_parser() -> argparse.ArgumentParser:

    parser = argparse.ArgumentParser(
        description=(
            "Home DIY Repair synthetic Q&A pipeline"
        )
    )

    sub = parser.add_subparsers(
        dest="command",
        required=True,
    )

    # --------------------------------------------------------
    # Benchmark
    # --------------------------------------------------------

    p = sub.add_parser(
        "inspect-benchmark"
    )

    p.add_argument(
        "--count",
        type=int,
        default=5,
    )

    p.add_argument(
        "--split",
        default="train",
    )

    # --------------------------------------------------------
    # Step 1
    # --------------------------------------------------------

    p = sub.add_parser(
        "generate"
    )

    p.add_argument(
        "--count-per-category",
        type=int,
        default=10,
    )

    p.add_argument(
        "--corrected",
        action="store_true",
    )

    p.add_argument(
        "--guidance",
    )

    # --------------------------------------------------------
    # Step 2
    # --------------------------------------------------------

    p = sub.add_parser(
        "gate"
    )

    p.add_argument(
        "--corrected",
        action="store_true",
    )

    p.add_argument(
        "--input",
        type=Path,
        default=None,
        help=(
            "Optional generated_qa_<timestamp>.jsonl. "
            "If omitted, the latest Step 1 artifact is used."
        ),
    )

    p.add_argument(
        "--no-semantic-dedup",
        action="store_true",
    )

    p.add_argument(
        "--semantic-threshold",
        type=float,
        default=SEMANTIC_DEDUP_THRESHOLD,
    )

    # --------------------------------------------------------
    # Step 3
    # --------------------------------------------------------

    p = sub.add_parser(
        "human-review"
    )

    p.add_argument(
        "--corrected",
        action="store_true",
    )

    p.add_argument(
        "--input",
        type=Path,
        default=None,
        help=(
            "Optional gated_<timestamp>.jsonl. "
            "If omitted, the latest Step 2 artifact is used."
        ),
    )

    p.add_argument(
        "--limit",
        type=int,
        default=20,
        help=(
            "Number of items to human-label. "
            "Use 0 to label all accepted items. "
            "Default: 20."
        ),
    )

    # --------------------------------------------------------
    # Step 4
    # --------------------------------------------------------

    p = sub.add_parser(
        "judge"
    )

    p.add_argument(
        "--corrected",
        action="store_true",
    )

    p.add_argument(
        "--input",
        type=Path,
        default=None,
        help=(
            "Optional human_labeled_<timestamp>.jsonl. "
            "If omitted, the latest Step 3 artifact is used."
        ),
    )

    # --------------------------------------------------------
    # Step 5
    # --------------------------------------------------------

    p = sub.add_parser(
        "analyze"
    )

    p.add_argument(
        "--corrected",
        action="store_true",
    )

    p.add_argument(
        "--input",
        type=Path,
        default=None,
        help=(
            "Optional judged_<timestamp>.jsonl. "
            "If omitted, the latest Step 4 artifact is used."
        ),
    )

    # --------------------------------------------------------
    # Step 6
    # --------------------------------------------------------

    p = sub.add_parser(
        "iterate"
    )

    p.add_argument(
        "--corrected",
        action="store_true",
    )

    p.add_argument(
        "--input",
        type=Path,
        default=None,
        help=(
            "Optional analysis_<timestamp>.json. "
            "If omitted, the latest Step 5 artifact is used."
        ),
    )

    # --------------------------------------------------------
    # Compare baseline/corrected
    # --------------------------------------------------------

    sub.add_parser(
        "compare"
    )

    # --------------------------------------------------------
    # Complete Steps 1-6
    # --------------------------------------------------------

    p = sub.add_parser(
        "all"
    )

    p.add_argument(
        "--count-per-category",
        type=int,
        default=10,
    )

    p.add_argument(
        "--corrected",
        action="store_true",
    )

    p.add_argument(
        "--guidance",
    )

    p.add_argument(
        "--human-label-count",
        type=int,
        default=20,
        help=(
            "Number of Step 2 passing items to human-label. "
            "Use 0 to label all."
        ),
    )

    p.add_argument(
        "--no-semantic-dedup",
        action="store_true",
    )

    p.add_argument(
        "--semantic-threshold",
        type=float,
        default=SEMANTIC_DEDUP_THRESHOLD,
    )

    return parser


# ============================================================
# Main
# ============================================================


def main() -> None:

    parser = build_parser()

    args = parser.parse_args()

    # --------------------------------------------------------
    # Benchmark inspection
    # --------------------------------------------------------

    if args.command == "inspect-benchmark":

        from benchmark.inspect_samples import (
            inspect,
        )

        inspect(
            args.count,
            args.split,
        )

    # --------------------------------------------------------
    # Step 1
    # --------------------------------------------------------

    elif args.command == "generate":

        run_step1(
            count_per_category=(
                args.count_per_category
            ),
            corrected=args.corrected,
            guidance=args.guidance,
        )

    # --------------------------------------------------------
    # Step 2
    # --------------------------------------------------------

    elif args.command == "gate":

        directory = get_data_directory(
            args.corrected
        )

        input_file = resolve_input_file(
            cli_input=args.input,
            directory=directory,
            prefix="generated_qa_",
            suffix=".jsonl",
        )

        run_step2(
            input_file=input_file,
            corrected=args.corrected,
            enable_semantic_dedup=(
                not args.no_semantic_dedup
            ),
            semantic_threshold=(
                args.semantic_threshold
            ),
        )

    # --------------------------------------------------------
    # Step 3
    # --------------------------------------------------------

    elif args.command == "human-review":

        directory = get_data_directory(
            args.corrected
        )

        input_file = resolve_input_file(
            cli_input=args.input,
            directory=directory,
            prefix="gated_",
            suffix=".jsonl",
        )

        run_step3(
            input_file=input_file,
            label_count=args.limit,
        )

    # --------------------------------------------------------
    # Step 4
    # --------------------------------------------------------

    elif args.command == "judge":

        directory = get_data_directory(
            args.corrected
        )

        input_file = resolve_input_file(
            cli_input=args.input,
            directory=directory,
            prefix="human_labeled_",
            suffix=".jsonl",
        )

        run_step4(
            input_file=input_file,
        )

    # --------------------------------------------------------
    # Step 5
    # --------------------------------------------------------

    elif args.command == "analyze":

        directory = get_data_directory(
            args.corrected
        )

        input_file = resolve_input_file(
            cli_input=args.input,
            directory=directory,
            prefix="judged_",
            suffix=".jsonl",
        )

        run_step5(
            input_file=input_file,
        )

    # --------------------------------------------------------
    # Step 6
    # --------------------------------------------------------

    elif args.command == "iterate":

        directory = get_data_directory(
            args.corrected
        )

        input_file = resolve_input_file(
            cli_input=args.input,
            directory=directory,
            prefix="analysis_",
            suffix=".json",
        )

        run_step6(
            input_file=input_file,
        )

    # --------------------------------------------------------
    # Compare
    # --------------------------------------------------------

    elif args.command == "compare":

        from pipeline.compare import (
            compare_runs,
        )

        baseline_directory = Path(
            BASELINE_DIR
        ).resolve()

        corrected_directory = Path(
            CORRECTED_DIR
        ).resolve()

        baseline_analysis = (
            find_latest_timestamped_file(
                baseline_directory,
                "analysis_",
                ".json",
            )
        )

        corrected_analysis = (
            find_latest_timestamped_file(
                corrected_directory,
                "analysis_",
                ".json",
            )
        )

        comparison_file = (
            create_output_file(
                corrected_directory,
                "comparison_",
                ".json",
            )
        )

        compare_runs(
            baseline_file=baseline_analysis,
            corrected_file=corrected_analysis,
            output_file=comparison_file,
        )

        print(
            f"Comparison report: "
            f"{comparison_file}"
        )

    # --------------------------------------------------------
    # Complete pipeline
    # --------------------------------------------------------

    elif args.command == "all":

        run_all_steps(
            count_per_category=(
                args.count_per_category
            ),
            corrected=args.corrected,
            guidance=args.guidance,
            human_label_count=(
                args.human_label_count
            ),
            enable_semantic_dedup=(
                not args.no_semantic_dedup
            ),
            semantic_threshold=(
                args.semantic_threshold
            ),
        )


if __name__ == "__main__":
    main()